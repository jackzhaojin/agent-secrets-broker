// Shared helpers for the sandbox scripts and the end-to-end test. Node 22, no dependencies.
// Nothing here prints a secret value: only labels (A-G) and short fingerprints.

import { execFileSync, spawn } from 'node:child_process';
import { createHash, randomBytes, randomInt } from 'node:crypto';
import { chmodSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const SECRETS_DIR = join(ROOT, '.secrets');
export const SANDBOX_FILE = join(SECRETS_DIR, 'sandbox.json');
export const PERSIST_DIR = join(ROOT, '.wrangler', 'state');
export const BROKER_CONFIG = join(ROOT, 'wrangler.jsonc');
export const MOCK_CONFIG = join(ROOT, 'mock-upstream', 'wrangler.jsonc');

/** What each dummy secret is for. The labels are safe to print; the values never are. */
export const ROLES = {
  A: 'Mock Git API key, version 1 (vault mockgit/api_key at seed; the upstream accepts it)',
  B: 'Mock Git API key, version 2 (the rotation target)',
  C: 'A wrong Mock Git key (put in the vault to force an upstream error)',
  D: 'Owner password (consent page and /admin sign-in)',
  E: 'Admin API token (bearer for /admin/api/*)',
  F: 'Cookie signing secret for /admin sessions',
  G: 'Canary in the vault (canary/unused) that no tool reads',
};

const ALPHABET = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789';
const WORDS = ('amber anchor apple arrow aspen atlas bamboo banjo basil beacon birch bison bloom bramble breeze brook cactus canyon cedar comet coral cosmos cricket ' +
  'delta dune ember falcon fern fjord flint forest galaxy garnet glacier granite harbor hazel heron indigo iris island jade jasper juniper kayak kelp lagoon ' +
  'lantern lemon lilac lotus maple marble meadow mesa mint nebula oak ocean olive onyx orbit orchid otter pebble pepper pine planet plum prairie quartz ' +
  'raven reef ridge river saffron sage sequoia sierra slate sparrow spruce summit tango thistle thunder tulip tundra valley velvet violet walnut willow zephyr').split(' ');

const randomString = (n) => Array.from(randomBytes(n), (b) => ALPHABET[b % ALPHABET.length]).join('');

function generate() {
  const words = Array.from({ length: 3 }, () => WORDS[randomInt(WORDS.length)]);
  return {
    A: `TEST_SECRET_A_${randomString(24)}`,
    B: `TEST_SECRET_B_${randomString(24)}`,
    C: `TEST_SECRET_C_${randomString(24)}`,
    // Typeable, because Jack types it on the consent page (possibly on a phone).
    D: `TEST_SECRET_D-${words.join('-')}-${randomInt(1000, 9999)}`,
    E: `TEST_SECRET_E_${randomString(32)}`,
    F: `TEST_SECRET_F_${randomString(40)}`,
    G: `TEST_SECRET_G_${randomString(24)}`,
  };
}

export const fingerprint = (value) => createHash('sha256').update(value).digest('hex').slice(0, 10);

export function loadSandbox({ create = false } = {}) {
  if (!existsSync(SANDBOX_FILE)) {
    if (!create) throw new Error(`No ${SANDBOX_FILE}. Run: npm run sandbox -- init`);
    mkdirSync(SECRETS_DIR, { recursive: true, mode: 0o700 });
    const data = { created: new Date().toISOString(), note: 'Dummy test secrets for the sandbox. Gitignored. Never commit.', values: generate() };
    writeFileSync(SANDBOX_FILE, JSON.stringify(data, null, 2) + '\n', { mode: 0o600 });
    chmodSync(SANDBOX_FILE, 0o600);
  }
  return JSON.parse(readFileSync(SANDBOX_FILE, 'utf8'));
}

/** Local `wrangler dev` reads the broker's Worker secrets from .dev.vars. */
export function writeDevVars(values) {
  const lines = [
    '# Generated by scripts/sandbox.mjs from .secrets/sandbox.json. Gitignored.',
    `OWNER_PASSWORD=${values.D}`,
    `ADMIN_TOKEN=${values.E}`,
    `COOKIE_SECRET=${values.F}`,
    'PUBLIC_BASE_URL=http://localhost:8787',
    'ENVIRONMENT=local',
  ];
  writeFileSync(join(ROOT, '.dev.vars'), lines.join('\n') + '\n', { mode: 0o600 });
}

export function wrangler(args, { input, quiet = true } = {}) {
  return execFileSync('npx', ['wrangler', ...args], {
    cwd: ROOT,
    input,
    encoding: 'utf8',
    stdio: [input === undefined ? 'ignore' : 'pipe', 'pipe', quiet ? 'pipe' : 'inherit'],
    env: { ...process.env, WRANGLER_SEND_METRICS: 'false' },
  });
}

/** Write a KV value without putting it on a command line (via a temp file that is removed). */
export function kvPut({ target, config, binding, key, value }) {
  const tmp = join(SECRETS_DIR, `.kv-${randomString(8)}`);
  writeFileSync(tmp, value, { mode: 0o600 });
  try {
    const where = target === 'remote' ? ['--remote'] : ['--local', '--persist-to', PERSIST_DIR];
    wrangler(['kv', 'key', 'put', key, '--path', tmp, '--binding', binding, '-c', config, ...where]);
  } finally {
    rmSync(tmp, { force: true });
  }
}

export function setVault({ target, values, label, ref = 'mockgit/api_key' }) {
  kvPut({ target, config: BROKER_CONFIG, binding: 'VAULT', key: ref, value: values[label] });
}

export function setUpstreamAccepted({ target, values, label }) {
  kvPut({ target, config: MOCK_CONFIG, binding: 'MOCK_KV', key: 'accepted_key', value: values[label] });
}

/** Push the broker's three Worker secrets in one request; the JSON goes over stdin. */
export function pushWorkerSecrets(values) {
  const json = JSON.stringify({ OWNER_PASSWORD: values.D, ADMIN_TOKEN: values.E, COOKIE_SECRET: values.F });
  wrangler(['secret', 'bulk', '-c', BROKER_CONFIG], { input: json });
}

export function seed({ target, values }) {
  setVault({ target, values, label: 'A' });
  kvPut({ target, config: BROKER_CONFIG, binding: 'VAULT', key: 'canary/unused', value: values.G });
  setUpstreamAccepted({ target, values, label: 'A' });
}

/**
 * docs/test-log.md: the sandbox e2e run on top (test/e2e.mjs), then one section per heading in
 * SECTION_ORDER: Claude Duet's own calls on the sandbox (test/duet.mjs), then the live checks
 * (test/live.mjs). Each script rewrites only its own part.
 */
export const TEST_LOG = join(ROOT, 'docs', 'test-log.md');
export const DUET_HEADING = '## Claude Duet on the sandbox';
export const LIVE_HEADING = '## Live broker';
const SECTION_ORDER = [DUET_HEADING, LIVE_HEADING];

export function writeTestLog({ sandbox, sections = {} }) {
  const current = existsSync(TEST_LOG) ? readFileSync(TEST_LOG, 'utf8') : '';
  const found = SECTION_ORDER.map((h) => [h, current.indexOf(`\n${h}\n`)]).filter(([, i]) => i >= 0).sort((a, b) => a[1] - b[1]);
  const top = found.length ? current.slice(0, found[0][1]) : current;
  const old = {};
  found.forEach(([h, i], k) => {
    old[h] = current.slice(i + 1, k + 1 < found.length ? found[k + 1][1] : undefined);
  });
  const parts = [(sandbox ?? top).trimEnd(), ...SECTION_ORDER.map((h) => (sections[h] ?? old[h] ?? '').trimEnd())].filter(Boolean);
  writeFileSync(TEST_LOG, parts.join('\n\n') + '\n');
}

/** Every place a value could show up, searched for every dummy secret. Returns hit counts by label. */
export function findSecrets(text, values) {
  const hits = {};
  for (const [label, value] of Object.entries(values)) {
    const n = text.split(value).length - 1;
    if (n) hits[label] = n;
  }
  return hits;
}

export function startProcess(cmd, args, logFile) {
  mkdirSync(dirname(logFile), { recursive: true });
  const child = spawn(cmd, args, { cwd: ROOT, env: { ...process.env, WRANGLER_SEND_METRICS: 'false' }, stdio: ['ignore', 'pipe', 'pipe'] });
  const chunks = [];
  child.stdout.on('data', (d) => chunks.push(d));
  child.stderr.on('data', (d) => chunks.push(d));
  return {
    child,
    output: () => Buffer.concat(chunks).toString('utf8'),
    stop: () => new Promise((res) => {
      if (child.exitCode !== null) return res();
      child.once('exit', res);
      child.kill('SIGINT');
      setTimeout(() => child.kill('SIGKILL'), 5000).unref();
    }),
    save: () => writeFileSync(logFile, Buffer.concat(chunks)),
  };
}
