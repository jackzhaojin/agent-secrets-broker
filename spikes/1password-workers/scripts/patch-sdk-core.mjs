// Generates patched/sdk-core.mjs from node_modules/@1password/sdk-core/nodejs/core.js
// so the wasm-bindgen "nodejs" glue runs in workerd:
//  - WASM comes from a build-time `import x from '...wasm'` (wrangler precompiles it to a
//    WebAssembly.Module) instead of fs.readFileSync + new WebAssembly.Module(bytes).
//  - TextEncoder/TextDecoder come from globals instead of require('util').
//  - `module.require` (used by getrandom's Node path) is shimmed to return node:crypto.
//  - Output is ESM with named exports, aliased in wrangler.jsonc.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = join(root, 'node_modules/@1password/sdk-core/nodejs');
const outDir = join(root, 'patched');
const lazy = process.argv.includes('--lazy');
let glue = readFileSync(join(srcDir, 'core.js'), 'utf8');

function replaceOnce(re, to, label) {
  const before = glue;
  glue = glue.replace(re, to);
  if (glue === before) throw new Error('patch anchor not found: ' + label);
}

replaceOnce(/^const \{ TextDecoder, TextEncoder \} = require\(`util`\);$/m,
  '// [patched] TextDecoder/TextEncoder are globals in workerd', 'util');

const tailRe = /const path = require\('path'\)\.join\(__dirname, 'core_bg\.wasm'\);\nconst bytes = require\('fs'\)\.readFileSync\(path\);\n\nconst wasmModule = new WebAssembly\.Module\(bytes\);\nconst wasmInstance = new WebAssembly\.Instance\(wasmModule, imports\);\nwasm = wasmInstance\.exports;\nmodule\.exports\.__wasm = wasm;\n\nwasm\.__wbindgen_start\(\);/;
const instantiate = `function __opInstantiate() {
  if (wasm) return;
  const __t0 = Date.now();
  const wasmInstance = new WebAssembly.Instance(__opWasmModule, imports);
  wasm = wasmInstance.exports;
  module.exports.__wasm = wasm;
  wasm.__wbindgen_start();
  globalThis.__opInstantiateMs = Date.now() - __t0;
}`;
replaceOnce(tailRe, lazy ? `// [patched] lazy instantiate\n${instantiate}` : `// [patched] eager instantiate\n${instantiate}\n__opInstantiate();`, 'wasm load');

const publicFns = [...glue.matchAll(/^module\.exports\.([a-z][a-zA-Z0-9_]*) = function/gm)].map(m => m[1]);
const wasmRel = './' + relative(outDir, join(srcDir, 'core_bg.wasm'));

const header = `// GENERATED by scripts/patch-sdk-core.mjs - do not edit
import __opWasmModule from '${wasmRel}';
import * as __opNodeCrypto from 'node:crypto';
const module = { exports: {}, require(id) {
  if (id === 'crypto' || id === 'node:crypto') return __opNodeCrypto;
  throw new Error('[patched sdk-core] require not supported: ' + id);
} };
`;
const footer = '\n' + publicFns.map(n => lazy
  ? `export function ${n}(...a) { __opInstantiate(); return module.exports.${n}(...a); }`
  : `export const ${n} = module.exports.${n};`).join('\n') + '\nexport { __opInstantiate };\n';

mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'sdk-core.mjs'), header + glue + footer);
console.log(`wrote patched/sdk-core.mjs (${lazy ? 'lazy' : 'eager'}), exports: ${publicFns.join(', ')}`);
